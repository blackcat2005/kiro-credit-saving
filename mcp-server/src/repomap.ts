import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, extname, basename } from "node:path";

export interface Symbol { name: string; kind: string; line: number }
export interface FileInfo { path: string; size: number; hash: string; symbols: Symbol[] }
export interface ModuleInfo { name: string; files: FileInfo[]; hash: string; description: string }

const IGNORE_DIRS = new Set(["node_modules", ".git", "dist", "build", "out", "target", "__pycache__", ".venv", ".next", "coverage"]);
const CONTEXT_DIR = ".kiro/context";
const MAX_FILE = 1_000_000;

const SYMBOL_RULES: Record<string, RegExp[]> = {
  ts: [/^\s*(?:export\s+)?(?:default\s+)?(?:async\s+)?(function|class|interface|type|enum)\s+([A-Za-z_$][\w$]*)/, /^\s*(?:export\s+)?(const)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:async\s*)?(?:\(|function)/],
  py: [/^\s*(?:async\s+)?(def|class)\s+([A-Za-z_]\w*)/],
  go: [/^(func)\s+(?:\([^)]*\)\s*)?([A-Za-z_]\w*)/, /^(type)\s+([A-Za-z_]\w*)/],
  rs: [/^\s*(?:pub\s+)?(fn|struct|enum|trait|impl)\s+([A-Za-z_]\w*)/],
  java: [/^\s*(?:public|private|protected)?\s*(?:static\s+)?(class|interface|enum)\s+([A-Za-z_]\w*)/],
  md: [/^(#{1,3})\s+(.+)$/],
};
const EXT_LANG: Record<string, string> = {
  ".ts": "ts", ".tsx": "ts", ".js": "ts", ".jsx": "ts", ".mjs": "ts", ".cjs": "ts",
  ".py": "py", ".go": "go", ".rs": "rs", ".java": "java", ".kt": "java", ".md": "md",
};

const sha = (s: string | Buffer) => createHash("sha1").update(s).digest("hex");

export function listFiles(root: string): string[] {
  try {
    const out = execFileSync("git", ["ls-files", "-co", "--exclude-standard"], { cwd: root, encoding: "utf8", maxBuffer: 64 << 20, stdio: ["ignore", "pipe", "ignore"] });
    const files = out.split("\n").filter(Boolean);
    if (files.length) return files.filter(keep).sort();
  } catch { /* not a git repo */ }
  const acc: string[] = [];
  const walk = (dir: string) => {
    for (const e of readdirSync(join(root, dir), { withFileTypes: true })) {
      const rel = dir ? `${dir}/${e.name}` : e.name;
      if (e.isDirectory()) { if (!IGNORE_DIRS.has(e.name)) walk(rel); }
      else acc.push(rel);
    }
  };
  walk("");
  return acc.filter(keep).sort();
}

function keep(p: string): boolean {
  if (p.startsWith(CONTEXT_DIR + "/")) return false;
  return !p.split("/").some((s) => IGNORE_DIRS.has(s));
}

export function extractSymbols(path: string, text: string): Symbol[] {
  const rules = SYMBOL_RULES[EXT_LANG[extname(path)] ?? ""];
  if (!rules) return [];
  const out: Symbol[] = [];
  text.split("\n").forEach((line, i) => {
    for (const r of rules) {
      const m = r.exec(line);
      if (m) { out.push({ kind: m[1].startsWith("#") ? "h" + m[1].length : m[1], name: m[2].trim(), line: i + 1 }); break; }
    }
  });
  return out.slice(0, 200);
}

export function moduleOf(path: string): string {
  const i = path.indexOf("/");
  return i < 0 ? "_root" : path.slice(0, i);
}

export function scan(root: string): ModuleInfo[] {
  const byMod = new Map<string, FileInfo[]>();
  for (const p of listFiles(root)) {
    let st; try { st = statSync(join(root, p)); } catch { continue; }
    if (!st.isFile()) continue;
    let hash = "", symbols: Symbol[] = [];
    if (st.size <= MAX_FILE) {
      const buf = readFileSync(join(root, p));
      hash = sha(buf);
      if (!buf.includes(0)) symbols = extractSymbols(p, buf.toString("utf8"));
    }
    const m = moduleOf(p);
    (byMod.get(m) ?? byMod.set(m, []).get(m)!).push({ path: p, size: st.size, hash, symbols });
  }
  return [...byMod.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([name, files]) => ({
    name, files,
    hash: sha(files.map((f) => f.path + f.hash).join("\n")),
    description: describe(root, name, files),
  }));
}

function describe(root: string, name: string, files: FileInfo[]): string {
  const langs = new Map<string, number>();
  for (const f of files) { const e = extname(f.path) || basename(f.path); langs.set(e, (langs.get(e) ?? 0) + 1); }
  const top = [...langs.entries()].sort((a, b) => b[1] - a[1]).slice(0, 3).map(([e, n]) => `${e}×${n}`).join(" ");
  const readme = files.find((f) => /(^|\/)readme\.md$/i.test(f.path));
  let hint = "";
  if (readme) {
    const l = readFileSync(join(root, readme.path), "utf8").split("\n").find((x) => x.trim() && !x.startsWith("#"));
    if (l) hint = " — " + l.trim().slice(0, 100);
  }
  return `${top}${hint}`;
}

const safe = (n: string) => n.replace(/[^\w.-]/g, "_");

export function renderIndex(mods: ModuleInfo[]): string {
  const lines = mods.map((m) => `- **${m.name}** (${m.files.length} files, #${m.hash.slice(0, 8)}): ${m.description} → modules/${safe(m.name)}.md`);
  return `# Repo map\n\nAuto-generated by kiro-credit-saver. Read modules/<name>.md only when needed.\n\n${lines.join("\n")}\n`;
}

export function renderModule(m: ModuleInfo): string {
  const body = m.files.map((f) => {
    const syms = f.symbols.slice(0, 40).map((s) => `${s.kind} ${s.name}:${s.line}`).join(", ");
    return `- ${f.path} (${f.size}B)${syms ? ": " + syms : ""}`;
  });
  return `# Module ${m.name} #${m.hash.slice(0, 8)}\n\n${body.join("\n")}\n`;
}

/** Rewrite only changed modules. Returns names of modules written. */
export function refresh(root: string): { mods: ModuleInfo[]; written: string[] } {
  const mods = scan(root);
  const dir = join(root, CONTEXT_DIR);
  const modDir = join(dir, "modules");
  mkdirSync(modDir, { recursive: true });
  const written: string[] = [];
  for (const m of mods) {
    const f = join(modDir, safe(m.name) + ".md");
    const cur = existsSync(f) ? readFileSync(f, "utf8").split("\n")[0] : "";
    if (!cur.endsWith(`#${m.hash.slice(0, 8)}`)) { writeFileSync(f, renderModule(m)); written.push(m.name); }
  }
  const idx = renderIndex(mods);
  const ip = join(dir, "index.md");
  if (!existsSync(ip) || readFileSync(ip, "utf8") !== idx) writeFileSync(ip, idx);
  return { mods, written };
}

export function findSymbol(mods: ModuleInfo[], query: string, limit = 30): string[] {
  const q = query.toLowerCase();
  const hits: string[] = [];
  for (const m of mods) for (const f of m.files) for (const s of f.symbols)
    if (s.name.toLowerCase().includes(q)) hits.push(`${f.path}:${s.line} ${s.kind} ${s.name}`);
  return hits.slice(0, limit);
}
